"""适配层的抽象接口（供 M3 的 CLI 打桩与集成测试使用）。"""

from __future__ import annotations

from typing import Dict, Iterable, List, Optional, Sequence, Tuple, runtime_checkable, Protocol


@runtime_checkable
class GitProtocol(Protocol):
    """git 适配（:class:`prlib.infra.git.Git`）。"""

    def current_branch(self) -> str: ...

    def head_sha(self) -> str: ...

    def porcelain(self) -> str: ...

    def is_dirty(self) -> bool: ...

    def is_ancestor(self, ancestor: str, descendant: str) -> bool: ...

    def file_history_chain(self, path: str, branch: str, main: str, limit: int = 50) -> bool: ...

    def fetch(self, remote: str = "origin", ref: str = "") -> object: ...

    def show_file(self, ref: str, path: str) -> Optional[str]: ...

    def list_unregistered_shas(self, registered: Iterable[str], base: str = "origin/main") -> List[str]: ...

    def cherry_pick(self, sha: str, dry_run: bool = False) -> object: ...

    def rebase_onto(self, main: str = "origin/main", dry_run: bool = False) -> object: ...

    def reset_hard(self, target: str = "origin/main", dry_run: bool = False) -> object: ...

    def push_force_with_lease(self, branch: str, dry_run: bool = False) -> object: ...

    def commit(self, paths: Sequence[str], message: str = "", dry_run: bool = False) -> object: ...

    def push(self, branch: str, dry_run: bool = False) -> object: ...


@runtime_checkable
class GhProtocol(Protocol):
    """gh 适配（:class:`prlib.infra.gh.Gh`）。"""

    def repo(self) -> str: ...

    def current_user(self) -> str: ...

    def is_repo_owner(self, login: str) -> bool: ...

    def list_collaborators(self) -> List[str]: ...

    def codeowners_rules(self, ref: str = "main") -> List[object]: ...

    def codeowners_owner(self, path: str, ref: str = "main") -> Optional[str]: ...

    def list_prs(self, state: str = "open", limit: int = 30) -> List[dict]: ...

    def open_pr(self, base: str, head: str, title: str, body: str = "", dry_run: bool = False) -> int: ...

    def pr_review(self, number: int, approve: bool = True, body: str = "", dry_run: bool = False) -> None: ...

    def pr_comment(self, number: int, body: str, dry_run: bool = False) -> None: ...

    def pr_merge(self, number: int, method: str = "merge", admin: bool = False, dry_run: bool = False) -> None: ...

    def create_issue(self, title: str, body: str = "", labels: Sequence[str] = (), dry_run: bool = False) -> int: ...

    def close_issue(self, number: int, dry_run: bool = False) -> None: ...

    def list_issues(self, labels: Sequence[str] = (), limit: int = 20, since_days: int = 0) -> List[dict]: ...

    def edit_issue_body(self, number: int, body: str, dry_run: bool = False) -> None: ...

    def run_workflow(self, workflow: str, inputs: Optional[Dict[str, str]] = None, dry_run: bool = False) -> None: ...

    def list_runs(self, workflow: str, limit: int = 10) -> List[dict]: ...

    def run_view(self, run_id: int) -> dict: ...


@runtime_checkable
class StatusStoreProtocol(Protocol):
    """status 分支（只读）。"""

    def ref(self) -> str: ...

    def fetch(self) -> object: ...

    def invalidate(self) -> None: ...

    def read_text(self, path: str) -> Optional[str]: ...

    def read_json(self, path: str): ...

    def active(self) -> dict: ...

    def latest(self) -> dict: ...

    def version(self) -> dict: ...

    def config_text(self) -> str: ...

    def config(self, user: str): ...


@runtime_checkable
class ActionsProtocol(Protocol):
    """Actions 协议。"""

    def trigger(
        self,
        op: str,
        payload: Optional[dict] = None,
        actor: str = "",
        nonce: Optional[str] = None,
        no_wait: bool = False,
        dry_run: bool = False,
    ): ...

    def wait_result(self, nonce: str, timeout: Optional[float] = None) -> dict: ...

    def read_result(self, nonce: str) -> dict: ...

    def trigger_scan(self, no_wait: bool = True, dry_run: bool = False) -> str: ...

    def start_twice_check(
        self,
        op: str,
        payload: Optional[dict] = None,
        actor: str = "",
        dry_run: bool = False,
        no_wait: bool = False,
    ) -> dict: ...
